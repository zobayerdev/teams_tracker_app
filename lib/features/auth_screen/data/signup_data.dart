import 'dart:convert';
import 'package:dio/dio.dart';
import 'package:location_tracker/networks/dio/dio.dart';
import 'package:location_tracker/networks/endpoints.dart';
import 'package:location_tracker/networks/exception_handler/data_source.dart';

final class SignupApi {
  static final SignupApi _singleton = SignupApi._internal();
  SignupApi._internal();
  static SignupApi get instance => _singleton;

  Future<Map> postSignup(dynamic data) async {
    try {
      Response response = await postHttp(Endpoints.signUpUrl(), data);
      if (response.statusCode == 200 || response.statusCode == 201) {
        Map resData = json.decode(json.encode(response.data));
        return resData;
      } else {
        throw DataSource.DEFAULT.getFailure();
      }
    } catch (error) {
      rethrow;
    }
  }
}

typedef SignupData = SignupApi;
typedef RegisterApi = SignupApi;
typedef RegisterData = SignupApi;
